function currentFleetLang() { return (window.CarinoLang && window.CarinoLang.current) || 'en'; }

function t(key) {
  const dict = I18N[currentFleetLang()];
  return (dict && dict[key]) || key;
}

function applyStaticI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    if (!el.dataset.i18nKey) el.dataset.i18nKey = el.textContent.trim().replace(/\s+/g, ' ');
    el.textContent = t(el.dataset.i18nKey);
  });
  // Strings that carry markup of our own (<strong>, <code>, <em>). The keys and
  // the translations both live in this file, so nothing user-supplied ever
  // reaches innerHTML here.
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    if (!el.dataset.i18nKey) el.dataset.i18nKey = el.innerHTML.trim().replace(/\s+/g, ' ');
    el.innerHTML = t(el.dataset.i18nKey);
  });
}

// Tooltips and placeholders, addressed explicitly by id.
const ATTR_I18N = [
  ['modeChip', 'title', 'Measurement state'],
  ['intervalSel', 'title', 'Time between probes for each target'],
  ['timeoutSel', 'title', 'Give up on a probe after'],
  ['btnRun', 'title', 'Start or stop measuring'],
  ['btnClear', 'title', 'Clear all samples and statistics'],
  ['btnLogScale', 'title', 'Log scale — use it when one target is far slower than the others'],
  ['logFilter', 'placeholder', 'Filter by target…'],
];
function applyAttrI18n() {
  ATTR_I18N.forEach(([id, attr, key]) => {
    const el = document.getElementById(id);
    if (el) el.setAttribute(attr, t(key));
  });
}

function applyI18n() {
  document.documentElement.lang = currentFleetLang();
  applyStaticI18n();
  applyAttrI18n();
}

document.addEventListener('DOMContentLoaded', applyI18n);
window.addEventListener('carino:langchange', applyI18n);

// carino-navbar.js greets through window.t; js/app.js reads the same handle.
window.t = t;
window.CarinoI18n = { t, apply: applyI18n };
